// Ports the landing design (designs/watercolor-landing.html, the source of truth) into the Next app.
//   CSS -> components/landing/watercolor/watercolor.css  every selector scoped under .wl, fonts via next/font variables
//   JS  -> components/landing/watercolor/runtime.js      the design's script minus the background preview switcher,
//                                                        asset paths routed through ASSET(), plus the fixes listed below
// Markup is NOT generated: mirror any HTML changes into WatercolorLanding.tsx by hand.
// usage: pnpm port:landing
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const L = fs.readFileSync(path.join(repo, 'designs/watercolor-landing.html'), 'utf8').split(/\r?\n/);
const out = path.join(repo, 'components/landing/watercolor');
const GENERATED = 'GENERATED by scripts/port-watercolor.mjs from designs/watercolor-landing.html. Do not edit: change the design file and run `pnpm port:landing`.';

// locate blocks by content, not line numbers, so a re-run after design edits still lands right
const idx = (re, from = 0) => { const i = L.findIndex((l, k) => k >= from && re.test(l)); if (i < 0) throw new Error('marker not found: ' + re); return i; };
const cssStart = idx(/^<style>$/) + 1, cssEnd = idx(/^<\/style>$/);
const varStart = idx(/background variants \(preview switcher\)/), varEnd = idx(/frameworks band: overlaps the hero fade/);
const jsStart = idx(/^<script>$/) + 1, jsEnd = idx(/^<\/script>$/, jsStart);
const swStart = idx(/Background preview switcher/, jsStart), swEnd = idx(/Navbar: contract on scroll/, jsStart);

/* ---------------- CSS ---------------- */
// keep the hero background frame + the chosen variant (J Â· city at dusk); drop the other variants and the switcher
const pick = re => { const l = L.slice(varStart, varEnd).find(x => re.test(x)); if (!l) throw new Error('variant rule not found: ' + re); return l; };
let css = [...L.slice(cssStart, varStart),
  '/* hero background: J Â· city at dusk (chosen 2026-11-11); the other preview variants stay in the design file */',
  ...L.slice(varStart + 1, varStart + 3),
  '.bgJ{display:block}',
  pick(/^\.paperVid\{/),
  pick(/^\.bgJ \.paperVid\{/),
  pick(/body\.bg-j \.ticker \.tcard/).replace(/^.*\{/, '.ticker .tcard{'),
  ...L.slice(varEnd, cssEnd)].join('\n');
if (/\.\.\/(assets|public)\//.test(css)) throw new Error('CSS references a local asset path');

const FONT = { Fraunces: 'var(--font-fraunces)', '"JetBrains Mono"': 'var(--font-jetbrains)', 'JetBrains Mono': 'var(--font-jetbrains)' };
const scopeSel = s => {
  s = s.trim();
  if (/^(:root|html|body)\b/.test(s)) return s.replace(/^(:root|html|body)/, '.wl');
  return '.wl ' + s;
};
const root = postcss.parse(css);
root.walkRules(r => {
  if (r.parent.type === 'atrule' && /keyframes$/.test(r.parent.name)) return;
  r.selectors = r.selectors.map(scopeSel);
});
root.walkDecls(d => {
  if (d.prop === 'font-family' || d.prop === 'font') {
    for (const [k, v] of Object.entries(FONT)) d.value = d.value.split(k).join(v);
    if (d.prop === 'font-family') d.value = d.value.replace(/(^|,)\s*Inter\b/, '$1var(--font-inter)');
  }
  // body's overflow-x:hidden would make the wrapper a scroll container (breaks sticky); clip does the same job without that
  if (d.parent.selector === '.wl' && d.prop === 'overflow-x') d.value = 'clip';
});
const extra = `
/* --- Next.js integration (not in the design file) --- */
/* the wrapper stands in for the design's <body> */
.wl{min-height:100vh;width:100%}
/* Tailwind preflight makes svg block-level and gives every element a solid 0 border; restore browser defaults where the design relies on them */
.wl svg{display:inline}
.wl :where(*){border-style:none}
/* the bare "ring" class is also a Tailwind utility (box-shadow ring) */
.wl .ring{box-shadow:none}
/* Lenis drives the scroll while it runs (it adds .lenis to <html>); native smooth scrolling from globals.css would animate each of its frames again */
html.lenis{scroll-behavior:auto!important}
/* explainer diagrams set font-family as an SVG attribute, which can't read next/font's variable */
.wl :where(#cx) svg text{font-family:var(--font-inter),system-ui,sans-serif}
`;
const header = `/* ${GENERATED}
   Every selector is scoped under .wl so none of this reaches the tenant app. */\n`;
const cssOut = header + root.toString() + '\n' + extra;

/* ---------------- JS ---------------- */
let js = [...L.slice(jsStart, swStart), ...L.slice(swEnd, jsEnd)].join('\n');
const rep = (a, b, n) => { const c = js.split(a).length - 1; if (n != null && c !== n) throw new Error(`expected ${n}x "${a}", found ${c}`); if (!c) throw new Error('not found: ' + a); js = js.split(a).join(b); };
rep('../assets/team/${img}', "${ASSET('team/'+img)}");
rep('../assets/standards/${f}', "${ASSET('standards/'+f)}");
js = js.replace(/'\.\.\/assets\/([^']+)'/g, (_, p) => `ASSET('${p}')`);
rep(`.font='11px "JetBrains Mono",monospace'`, ".font='11px '+MONO", 1);
rep('if(!window.lottie)return', 'if(!lottie)return', 1); // lottie arrives as an import, not a CDN global
// removing the loader pauses the video, which fires one last timeupdate after #introProg has left the DOM
rep("if(v.duration)$('#introProg').style.width=", "const p=$('#introProg');if(v.duration&&p)p.style.width=", 1);
// India map: the bundler can't follow a runtime import of a CDN URL, so India's outline ships as india.json
// (Natural Earth 1:110m via world-atlas@2.0.2 countries-110m, feature id 356, coordinates rounded to 0.01Â°)
{ const re = /import\('https:\/\/cdn\.jsdelivr\.net\/npm\/topojson-client[^']*'\)\.then\(async topo=>\{\s*const w=await \(await fetch\('[^']*countries-110m\.json'\)\)\.json\(\);\s*const f=topo\.feature\([^;]*;/;
  if (!re.test(js)) throw new Error('India map loader not found'); js = js.replace(re, 'Promise.resolve().then(()=>{const f={geometry:INDIA};'); }
// CBAM background (measured: redrew at display refresh, ~39% main-thread busy while on screen). Same look, far less work:
// half-resolution backing store (soft gradient, upscale invisible), no MSAA, 30fps cap. Uniforms keep logical size so the pattern is unchanged.
rep("(()=>{const box=document.querySelector('#before-after .ba-bg');if(!box)return;",
    "(()=>{const box=document.querySelector('#before-after .ba-bg');if(!box)return;const BG_Q=.5,BG_FRAME=1000/30;", 1);
rep("canvas.getContext('webgl',{antialias:true})", "canvas.getContext('webgl',{antialias:false,powerPreference:'low-power'})", 1);
rep("this.canvas.width=w;this.canvas.height=hh;this.gl.viewport(0,0,w,hh);",
    "this.canvas.width=Math.ceil(w*BG_Q);this.canvas.height=Math.ceil(hh*BG_Q);this.gl.viewport(0,0,this.canvas.width,this.canvas.height);", 1);
rep("const animate=ts=>{raf=vis?requestAnimationFrame(animate):0;time+=",
    "const animate=ts=>{raf=vis?requestAnimationFrame(animate):0;if(last&&ts-last<BG_FRAME-1)return;time+=", 1);
// India map loop redrew ~2000 dots every frame while tab 04 stayed mounted, even scrolled far away: pause it off screen
rep("let t0=performance.now();\n  (function frame(t){if(!document.getElementById('indiaMap'))return;",
    "let t0=performance.now(),mapVis=true,mapRaf=0;\n  const mapIO=new IntersectionObserver(([e])=>{mapVis=e.isIntersecting;if(mapVis&&!mapRaf&&document.getElementById('indiaMap')===cv)mapRaf=requestAnimationFrame(frame)});mapIO.observe(cv);\n  function frame(t){mapRaf=0;if(document.getElementById('indiaMap')!==cv){mapIO.disconnect();return}if(!mapVis)return;", 1);
rep("requestAnimationFrame(frame)})(t0)}", "mapRaf=requestAnimationFrame(frame)}frame(t0)}", 1);
const left = js.match(/\.\.\/(?:assets|public)\/[^'"`)\s]*/g);
if (left) throw new Error('unrouted asset paths: ' + [...new Set(left)].join(', '));

// self-check: every element id the script looks up must exist in the JSX markup or in markup the script builds itself
const MARKUP = ['WatercolorLanding.tsx', 'SiteChrome.tsx']; // the landing page plus the shared navbar and footer
const tsx = MARKUP.map(f => fs.readFileSync(path.join(out, f), 'utf8')).join('\n');
const used = new Set([...js.matchAll(/\$\('#([\w-]+)'\)|getElementById\('([\w-]+)'\)|querySelector\('#([\w-]+)/g)].map(m => m[1] || m[2] || m[3]));
const defined = new Set([...(tsx + js).matchAll(/\bid=["']([\w-]+)["']/g)].map(m => m[1]));
const missing = [...used].filter(id => !defined.has(id));
if (missing.length) throw new Error(`script looks up ids missing from ${MARKUP.join(' / ')}: ` + missing.join(', '));

const PARAMS = ['window', 'document', 'addEventListener', 'removeEventListener', 'setTimeout', 'setInterval', 'requestAnimationFrame',
  'IntersectionObserver', 'ResizeObserver', 'MutationObserver', 'lottie', 'ASSET', 'MONO', 'INDIA'];
const jsOut = `/* eslint-disable */
// ${GENERATED}
// Plain DOM code: WatercolorLanding renders the markup, then calls run() with a sandboxed window/document/timers/observers
// (see sandbox.ts) so everything it starts is torn down on unmount.
export function run({ ${PARAMS.join(', ')} }) {
${js}
}
`;

fs.writeFileSync(path.join(out, 'watercolor.css'), cssOut);
fs.writeFileSync(path.join(out, 'runtime.js'), jsOut);
console.log(`ported: watercolor.css ${(cssOut.length / 1024).toFixed(0)}KB, runtime.js ${(jsOut.length / 1024).toFixed(0)}KB, ${used.size} element ids checked`);
